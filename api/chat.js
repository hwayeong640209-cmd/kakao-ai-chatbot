import fs from "fs";
import path from "path";
import { GoogleGenAI } from "@google/genai";

export default async function handler(req, res) {

  // =====================================================
  // CORS
  // =====================================================

  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader(
    "Access-Control-Allow-Methods",
    "POST, OPTIONS"
  );
  res.setHeader(
    "Access-Control-Allow-Headers",
    "Content-Type"
  );

  if (req.method === "OPTIONS") {
    return res.status(200).end();
  }

  if (req.method !== "POST") {
    return res.status(405).json({
      answer: "POST 요청만 가능합니다."
    });
  }

  try {

    // =====================================================
    // 1. 사용자 질문 확인
    // =====================================================

    const { message } = req.body || {};

    if (!message || !message.trim()) {
      return res.status(400).json({
        answer: "질문을 입력해주세요."
      });
    }

    // =====================================================
    // 2. 챗봇22.txt 읽기
    // =====================================================

    const filePath = path.join(
      process.cwd(),
      "data",
      "챗봇22.txt"
    );

    if (!fs.existsSync(filePath)) {
      console.error(
        "업무자료 파일을 찾을 수 없습니다:",
        filePath
      );

      return res.status(500).json({
        answer:
          "서버에서 업무자료를 찾을 수 없습니다. Vercel의 data/챗봇22.txt 파일을 확인해주세요."
      });
    }

    const knowledge = fs.readFileSync(
      filePath,
      "utf8"
    );

    // =====================================================
    // 3. API Key 확인
    // =====================================================

    const apiKey = process.env.GEMINI_API_KEY;

    if (!apiKey) {
      console.error(
        "GEMINI_API_KEY가 없습니다."
      );

      return res.status(500).json({
        answer:
          "Gemini API Key가 서버에 설정되지 않았습니다."
      });
    }

    // =====================================================
    // 4. Gemini SDK 생성
    // =====================================================

    const ai = new GoogleGenAI({
      apiKey: apiKey
    });

    // =====================================================
    // 5. 챗봇 시스템 지침
    // =====================================================

    const systemInstruction = `

당신은 한국도로교통공단 전남운전면허시험장
업무 안내 전문 챗봇입니다.

사용자의 질문을 이해하고,
아래 제공되는 [업무자료]를 근거로
일반인이 이해하기 쉽게 답변하세요.


====================================================
[가장 중요한 원칙]
====================================================

1. 반드시 [업무자료]를 가장 우선적인 근거로 사용하세요.

2. [업무자료]에 없는 내용을 사실처럼 만들어내지 마세요.

3. 인터넷이나 일반적인 운전면허 상식보다
   [업무자료]의 내용을 우선하세요.

4. [업무자료]에서 질문에 대한 정확한 내용을
   확인할 수 없는 경우에는 다음과 같이 답변하세요.

"현재 제공된 업무자료에서는 정확한 내용을 확인하기 어렵습니다."

5. 존재하지 않는 절차, 시험, 준비물, 수수료 등을
   임의로 만들어내지 마세요.


====================================================
[질문의 의미를 이해하세요]
====================================================

사용자가 정확한 행정용어를 사용하지 않아도
질문의 의도를 파악하세요.

예를 들어,

"1종보통 있는데 2종소형 따고 싶어요"

라고 질문하면

→ 1종보통 면허 소지자의
   2종소형 추가취득에 관한 질문

으로 이해하세요.


"오토바이 면허 따려면?"

→ 2종소형 또는 원동기장치자전거
   관련 질문인지 업무자료를 확인하세요.


"75살인데 면허 갱신 어떻게 해?"

→ 만75세 이상 운전자의
   적성검사 및 갱신 절차 관련 질문으로 이해하세요.


"치매검사 꼭 해야 해?"

→ 고령운전자 적성검사 및
   치매선별검사 관련 내용인지 확인하세요.


"필기시험 인터넷으로 예약돼?"

→ 학과시험 접수방법 관련 질문으로 이해하세요.


즉,

사용자가 전문용어를 정확하게 사용하지 않아도
질문의 의도를 먼저 파악한 다음
업무자료에서 관련 내용을 찾아 답변하세요.


====================================================
[답변 작성 방법]
====================================================

답변은 가능하면 다음 순서로 구성하세요.

① 핵심 답변

② 절차

③ 면제되는 시험 / 필요한 시험

④ 준비물

⑤ 수수료

⑥ 예약 / 접수 방법

⑦ 주의사항

단,

질문과 관계없는 항목은 억지로 추가하지 마세요.


====================================================
[여러 정보를 연결하세요]
====================================================

질문 하나에 여러 정보가 필요한 경우
업무자료의 여러 내용을 연결하여
하나의 완성된 답변을 만들어주세요.


예:

"1종보통 가지고 있는데 2종소형 따고 싶어요"

라고 질문했다면

단순히

"기능시험을 보시면 됩니다."

라고 끝내지 마세요.


업무자료에 관련 내용이 있다면

- 추가취득 여부
- 응시전 교통안전교육
- 신체검사
- 학과시험
- 기능시험
- 기능시험 수수료
- 시험 장소
- 재응시 조건

등을 확인하여
사용자에게 필요한 내용을 함께 설명하세요.


단, 위 항목이 실제 업무자료에 존재하는 경우에만
답변에 포함하세요.


====================================================
[쉬운 말로 설명하세요]
====================================================

공무원 문서처럼 딱딱하게 답변하지 마세요.

일반인이 이해하기 쉬운 표현을 사용하세요.


예:

"1종보통 면허를 가지고 계시다면
처음 면허를 취득하는 경우와 달리
일부 교육이나 시험이 면제될 수 있습니다.

정확한 면제 여부는 업무자료의
응시조건을 기준으로 확인해야 합니다."

처럼 자연스럽게 설명하세요.


====================================================
[교육을 반드시 구분하세요]
====================================================

다음 교육을 혼동하지 마세요.

- 응시전 교통안전교육
- 특별교통안전교육
- 고령운전자 교통안전교육

각 교육은 대상과 목적이 다릅니다.

질문에 맞는 교육을
업무자료에서 확인하여 답변하세요.


====================================================
[고령운전자 질문]
====================================================

만75세 이상 적성검사와 관련된 질문에서는
업무자료에 관련 내용이 있다면

- 치매선별검사
- 고령운전자 교통안전교육
- 적성검사
- 시험장
- 경찰서
- 온라인 신청

등의 내용을 서로 연결해서 설명하세요.

단, 업무자료에 없는 내용은 추가하지 마세요.


====================================================
[답변 스타일]
====================================================

답변은 다음처럼 작성하면 좋습니다.

핵심:
질문에 대한 가장 중요한 답변을 먼저 설명합니다.

절차:
1. ...
2. ...
3. ...

준비물:
- ...
- ...

수수료:
- ...

참고:
- ...


질문에 따라 필요한 항목만 사용하세요.

너무 짧게 답하지 말고,
그렇다고 질문과 관계없는 정보를
장황하게 설명하지도 마세요.

사용자가 실제로 시험장에 방문했을 때
도움이 될 수 있는 수준으로 설명하세요.


====================================================
[업무자료]
====================================================

${knowledge}

====================================================
[업무자료 끝]
====================================================


마지막으로 다시 한 번 강조합니다.

당신의 지식보다 [업무자료]를 우선하세요.

[업무자료]에 없는 내용을 추측해서 답하지 마세요.

확실하지 않은 경우에는
"현재 제공된 업무자료에서는 정확한 내용을 확인하기 어렵습니다."
라고 답변하세요.

`;

    // =====================================================
    // 6. Gemini 호출
    // =====================================================

    const response = await ai.models.generateContent({

      model: "gemini-3.5-flash",

      contents: message,

      config: {
        systemInstruction: systemInstruction
      }

    });

    // =====================================================
    // 7. 답변 추출
    // =====================================================

    const answer = response.text;

    if (!answer || !answer.trim()) {

      console.error(
        "Gemini 응답에 텍스트가 없습니다.",
        response
      );

      return res.status(500).json({
        answer:
          "질문에 대한 답변을 생성하지 못했습니다. 질문을 조금 다르게 입력해 주세요."
      });
    }

    // =====================================================
    // 8. 정상 응답
    // =====================================================

    return res.status(200).json({
      answer: answer.trim()
    });

  } catch (error) {

    // =====================================================
    // 9. 상세 오류 출력
    // =====================================================

    console.error(
      "===================================="
    );

    console.error(
      "Gemini 챗봇 오류"
    );

    console.error(
      error
    );

    console.error(
      "===================================="
    );

    // 개발/디버깅을 위해 실제 오류 내용을 반환
    const errorMessage =
      error?.message ||
      String(error);

    return res.status(500).json({

      answer:
        "Gemini 처리 중 오류가 발생했습니다.\n\n" +
        "오류 내용: " +
        errorMessage

    });

  }
}
