import fs from "fs";
import path from "path";

export default async function handler(req, res) {
  // =====================================================
  // CORS
  // =====================================================

  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader(
    "Access-Control-Allow-Methods",
    "POST, OPTIONS"
  );
  res.setHeader(
    "Access-Control-Allow-Headers",
    "Content-Type"
  );

  if (req.method === "OPTIONS") {
    return res.status(200).end();
  }

  if (req.method !== "POST") {
    return res.status(405).json({
      answer: "POST 요청만 가능합니다."
    });
  }

  try {
    // =====================================================
    // 1. 사용자 질문 확인
    // =====================================================

    const { message } = req.body || {};

    if (!message || !message.trim()) {
      return res.status(400).json({
        answer: "질문을 입력해주세요."
      });
    }

    const userMessage = message.trim();

    // =====================================================
    // 2. 간단한 인사 처리
    // =====================================================

    const greetings = [
      "안녕",
      "안녕하세요",
      "안녕하세요!",
      "안녕하세용",
      "하이",
      "반가워",
      "반갑습니다"
    ];

    if (
      greetings.some((greeting) =>
        userMessage.startsWith(greeting)
      )
    ) {
      return res.status(200).json({
        answer:
          "안녕하세요! 😊\n\n전남운전면허시험장 관련해서 궁금한 내용을 편하게 질문해주세요.\n\n예를 들어\n• 운전면허 취득 절차\n• 적성검사·갱신\n• 기능시험\n• 고령운전자 면허 갱신\n• 면허별 시험 면제\n• 시험장 위치 및 운영시간\n• 준비물과 수수료\n등을 안내해 드릴 수 있습니다."
      });
    }

    // =====================================================
    // 3. 챗봇22.txt 읽기
    // =====================================================

    const filePath = path.join(
      process.cwd(),
      "data",
      "챗봇22.txt"
    );

    if (!fs.existsSync(filePath)) {
      console.error(
        "챗봇22.txt 파일을 찾을 수 없습니다:",
        filePath
      );

      return res.status(500).json({
        answer:
          "업무자료 파일을 찾을 수 없습니다. 관리자에게 문의해주세요."
      });
    }

    const knowledge = fs.readFileSync(
      filePath,
      "utf8"
    );

    // =====================================================
    // 4. Gemini API Key
    // =====================================================

    const apiKey = process.env.GEMINI_API_KEY;

    if (!apiKey) {
      console.error(
        "GEMINI_API_KEY 환경변수가 없습니다."
      );

      return res.status(500).json({
        answer:
          "AI 서비스 설정을 확인해주세요."
      });
    }

    // =====================================================
    // 5. Gemini에게 전달할 시스템 지침
    // =====================================================

    const systemInstruction = `
당신은 한국도로교통공단 전남운전면허시험장의
운전면허 업무 안내 전문 챗봇입니다.

당신에게 제공되는 [업무자료]를 가장 중요한 답변 근거로 사용하세요.

====================================================
[가장 중요한 원칙]
====================================================

1. 답변은 반드시 [업무자료]를 기준으로 합니다.

2. [업무자료]에 없는 내용을 임의로 만들어내지 마세요.

3. 일반적인 운전면허 상식과 [업무자료]의 내용이 다를 경우
   [업무자료]의 내용을 우선합니다.

4. [업무자료]에서 정확한 답을 찾을 수 없는 경우에는
   추측해서 답하지 말고 다음과 같이 안내하세요.

"현재 제공된 업무자료에서는 정확한 내용을 확인하기 어렵습니다."

5. 사용자가 질문을 짧거나 일상적인 표현으로 하더라도
   질문의 의도를 파악해서 관련 업무자료를 찾아 답변하세요.

====================================================
[질문의 의도를 파악하는 방법]
====================================================

사용자가 정확한 행정용어를 사용하지 않아도 됩니다.

예를 들어,

"1종보통 있는데 2종소형 따고 싶어요"
→ 1종보통 소지자의 2종소형 추가취득

"오토바이 면허 따려면?"
→ 원동기장치자전거 또는 2종소형 관련 질문

"75살인데 면허 갱신 어떻게 해?"
→ 만75세 이상 운전자의 적성검사·갱신

"75세인데 교육만 받으면 돼?"
→ 고령운전자 교통안전교육 + 치매검사 + 적성검사 절차

"치매검사 꼭 해야 해?"
→ 만75세 이상 적성검사 대상자의 치매선별검사

"필기시험 인터넷 예약돼?"
→ 학과시험 접수방법

"기능시험 예약하고 싶어"
→ 장내기능시험 접수방법 및 온라인 예약

"면허증 잃어버렸어"
→ 운전면허증 재발급 관련 안내

처럼 사용자의 표현을 업무자료의 정확한 업무로 연결하세요.

====================================================
[답변은 한 문장으로 끝내지 마세요]
====================================================

사용자의 질문에 여러 정보가 관련되어 있다면
업무자료의 여러 항목을 연결해서 종합적으로 답변하세요.

특히 다음과 같은 정보를 관련성이 있을 때 함께 안내하세요.

① 핵심 답변
② 진행 절차
③ 면제되는 시험
④ 응시해야 하는 시험
⑤ 준비물
⑥ 수수료
⑦ 예약 및 접수방법
⑧ 시험장 위치
⑨ 시험시간
⑩ 재응시 조건
⑪ 주의사항

단, 질문과 관계없는 정보까지 무조건 모두 나열하지 마세요.

====================================================
[면허 추가취득 질문]
====================================================

기존 면허를 가지고 다른 면허를 추가로 취득하는 질문에서는
"처음 면허를 취득하는 사람"과 동일하게 답하지 마세요.

반드시 기존 면허와 취득하려는 면허를 구분하여
업무자료에 있는 면제과목과 응시과목을 확인하세요.

예를 들어

"1종보통을 가지고 있는데 2종소형을 따고 싶어요."

라는 질문에는 단순히
"기능시험을 보시면 됩니다."
라고만 답하지 마세요.

업무자료에서 확인되는 경우,

- 추가취득자 여부
- 응시전 교통안전교육 면제 여부
- 신체검사 면제 여부
- 학과시험 면제 여부
- 기능시험 응시 여부
- 기능시험 수수료
- 시험장 위치
- 재응시 조건

등을 연결해서 설명하세요.

====================================================
[교통안전교육 구분]
====================================================

다음 교육을 혼동하지 마세요.

1. 응시전 교통안전교육
2. 특별교통안전교육
3. 고령운전자 교통안전교육

각 교육의 대상과 목적은 반드시 업무자료에 따라 구분하세요.

특히 기존 운전면허 소지자의 추가취득과
처분에 따른 특별교통안전교육,
만75세 이상 고령운전자의 교육을 서로 혼동하지 마세요.

====================================================
[만75세 이상 질문]
====================================================

만75세 이상 운전자의 적성검사·갱신 질문에서는
"고령운전자 교육만 받으면 된다"고 단순하게 답하지 마세요.

업무자료에 관련 절차가 있다면

치매검사
→ 고령운전자 의무교육
→ 시험장/경찰서 방문 또는 온라인 적성검사 신청

등 전체적인 절차를 설명하세요.

치매검사, 교육, 적성검사의 관계를 명확하게 설명하세요.

====================================================
[쉬운 말로 설명]
====================================================

공무원 내부 문서처럼 딱딱하게 답하지 말고
일반 운전면허 민원인이 이해하기 쉽게 설명하세요.

예:

"1종보통 면허를 이미 가지고 계시다면
처음 면허를 취득하는 경우가 아니기 때문에
응시전 교통안전교육은 다시 받지 않으셔도 됩니다."

처럼 자연스럽게 설명하세요.

====================================================
[답변 구조]
====================================================

질문에 따라 필요한 경우 다음 구조를 사용하세요.

핵심:
질문에 대한 가장 중요한 답변을 먼저 설명합니다.

절차:
1. ...
2. ...
3. ...

준비물:
- ...
- ...

수수료:
- ...

참고:
- ...

모든 항목을 무조건 사용할 필요는 없습니다.

====================================================
[절대 하지 말아야 할 것]
====================================================

- 업무자료에 없는 내용을 사실처럼 말하지 마세요.
- 면제되지 않은 시험을 면제라고 하지 마세요.
- 필요한 절차를 생략하지 마세요.
- 서로 다른 교통안전교육을 혼동하지 마세요.
- 존재하지 않는 예약방법이나 수수료를 만들지 마세요.
- 사용자가 질문하지 않은 내용을 지나치게 길게 설명하지 마세요.
- "현재 답변을 처리하는 데 일시적인 문제가 발생했습니다."
라는 문구를 정상적인 답변으로 사용하지 마세요.
- 답을 모르면 추측하지 말고 업무자료에서 확인할 수 없다고 안내하세요.

====================================================
[업무자료 시작]
====================================================

${knowledge}

====================================================
[업무자료 끝]
====================================================
`;

    // =====================================================
    // 6. Gemini API 호출
    // =====================================================

    const model = "gemini-3.5-flash";

    const url =
      "https://generativelanguage.googleapis.com/v1beta/models/" +
      model +
      ":generateContent?key=" +
      encodeURIComponent(apiKey);

    const response = await fetch(url, {
      method: "POST",

      headers: {
        "Content-Type": "application/json"
      },

      body: JSON.stringify({
        system_instruction: {
          parts: [
            {
              text: systemInstruction
            }
          ]
        },

        contents: [
          {
            role: "user",

            parts: [
              {
                text: userMessage
              }
            ]
          }
        ],

        generationConfig: {
          maxOutputTokens: 1200
        }
      })
    });

    // =====================================================
    // 7. Gemini 응답 확인
    // =====================================================

    const data = await response.json();

    if (!response.ok) {
      console.error(
        "Gemini API 오류:",
        JSON.stringify(data, null, 2)
      );

      return res.status(500).json({
        answer:
          "AI 답변 처리 중 오류가 발생했습니다. 잠시 후 다시 질문해주세요."
      });
    }

    // =====================================================
    // 8. 답변 추출
    // =====================================================

    const answer =
      data?.candidates?.[0]?.content?.parts
        ?.map((part) => part.text || "")
        .join("")
        .trim();

    if (!answer) {
      console.error(
        "Gemini 응답에 답변이 없습니다:",
        JSON.stringify(data, null, 2)
      );

      return res.status(500).json({
        answer:
          "질문에 대한 답변을 찾지 못했습니다. 질문을 조금 다르게 입력해 주세요."
      });
    }

    // =====================================================
    // 9. 최종 답변
    // =====================================================

    return res.status(200).json({
      answer
    });

  } catch (error) {
    console.error(
      "서버 오류:",
      error
    );

    return res.status(500).json({
      answer:
        "서버에서 답변을 처리하는 중 문제가 발생했습니다."
    });
  }
}
