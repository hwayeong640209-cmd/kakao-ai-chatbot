import fs from "fs";
import path from "path";
import { GoogleGenAI } from "@google/genai";

const ai = new GoogleGenAI({
  apiKey: process.env.GEMINI_API_KEY,
});

export default async function handler(req, res) {
  // =====================================================
  // CORS
  // =====================================================

  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader(
    "Access-Control-Allow-Methods",
    "POST, OPTIONS"
  );
  res.setHeader(
    "Access-Control-Allow-Headers",
    "Content-Type"
  );

  if (req.method === "OPTIONS") {
    return res.status(200).end();
  }

  // =====================================================
  // POST만 허용
  // =====================================================

  if (req.method !== "POST") {
    return res.status(405).json({
      answer: "POST 요청만 가능합니다.",
    });
  }

  try {
    // =====================================================
    // 1. 사용자 질문
    // =====================================================

    const { message } = req.body || {};

    if (!message || typeof message !== "string") {
      return res.status(400).json({
        answer: "질문을 입력해주세요.",
      });
    }

    // =====================================================
    // 2. 챗봇22.txt 읽기
    // =====================================================

    const filePath = path.join(
      process.cwd(),
      "knowledge",
      "챗봇22.txt"
    );

    const knowledge = fs.readFileSync(
      filePath,
      "utf8"
    );

    // =====================================================
    // 3. 시스템 지침
    // =====================================================

    const systemInstruction = `
당신은 한국도로교통공단 전남운전면허시험장
업무 안내 전문 챗봇입니다.

당신이 답변할 때 사용할 수 있는 공식 업무자료는
아래에 제공된 "챗봇22.txt" 하나뿐입니다.

==================================================
가장 중요한 원칙
==================================================

1. 반드시 챗봇22.txt를 근거로 답변하세요.

2. 챗봇22.txt에 없는 내용을 사실처럼 만들어내지 마세요.

3. 일반적인 인터넷 지식이나 운전면허 상식을
   챗봇22.txt보다 우선해서 사용하지 마세요.

4. 챗봇22.txt에서 질문에 대한 정확한 내용을
   찾을 수 없는 경우 다음과 같이 답변하세요.

"현재 제공된 업무자료에서는 정확한 내용을
확인하기 어렵습니다."

5. 질문에 답하기 위해 챗봇22.txt의 여러 내용을
   함께 연결해야 하는 경우에는 관련된 내용을
   종합해서 하나의 답변으로 만들어주세요.

==================================================
질문의 의미를 이해하는 방법
==================================================

사용자가 업무용어를 정확하게 사용하지 않아도
질문의 의도를 파악해서 챗봇22.txt의 내용과
연결하세요.

예를 들어,

"오토바이 면허 따려면?"
→ 챗봇22.txt에서 관련 면허 취득 내용을 찾아 답변

"면허 갱신 어떻게 해?"
→ 해당 면허 종류와 연령 조건을 파악하여
   챗봇22.txt의 갱신 관련 내용을 찾아 답변

"75살인데 면허 갱신해야 해?"
→ 챗봇22.txt의 고령운전자 관련 내용을 찾아
   해당 절차를 설명

"필기시험 전에 뭐 해야 해?"
→ 챗봇22.txt의 응시전 교통안전교육 및
   학과시험 관련 내용을 찾아 설명

단, 위 예시는 질문을 해석하는 방법을 설명하기 위한
것이며 실제 답변 내용은 반드시 챗봇22.txt에
있는 정보만 사용하세요.

==================================================
답변 방법
==================================================

사용자가 질문하면 먼저 질문의 핵심을 파악하세요.

가능하면 다음 순서로 답변하세요.

[핵심]
질문에 대한 가장 중요한 답변을 먼저 알려주세요.

[절차]
필요한 경우 순서대로 설명하세요.

1.
2.
3.

[준비물]
챗봇22.txt에 관련 내용이 있다면 알려주세요.

[수수료]
챗봇22.txt에 관련 내용이 있다면 알려주세요.

[주의사항]
챗봇22.txt에 관련 내용이 있다면 알려주세요.

모든 항목을 무조건 사용할 필요는 없습니다.

질문이 단순하다면 짧게 답변하세요.

질문이 복잡하다면 관련 정보를 연결해서
충분히 설명하세요.

==================================================
답변 스타일
==================================================

공무원 문서처럼 지나치게 딱딱하게 답하지 마세요.

일반인이 이해하기 쉬운 말로 설명하세요.

예:

"1종보통 면허를 이미 가지고 계신 경우에는
처음 면허를 취득하는 것이 아니므로
응시전 교통안전교육 대상이 아닙니다."

처럼 자연스럽게 설명하세요.

단, 위 문장 자체를 사실로 사용하지 말고
반드시 챗봇22.txt에서 확인되는 경우에만
그 내용을 답변하세요.

==================================================
중요한 구분
==================================================

챗봇22.txt에 나오는

- 응시전 교통안전교육
- 특별교통안전교육
- 고령운전자 교통안전교육

등은 서로 다른 교육일 수 있으므로
임의로 같은 교육이라고 설명하지 마세요.

반드시 챗봇22.txt의 내용을 기준으로 구분하세요.

==================================================
고령운전자 질문
==================================================

고령운전자 관련 질문에서는
챗봇22.txt에 관련 정보가 있다면
단순히 "교육을 받으세요"라고만 하지 말고

검사
→ 교육
→ 적성검사 또는 갱신

등 챗봇22.txt에서 확인되는 절차를
가능한 한 연결해서 설명하세요.

단, 자료에 없는 절차는 추가하지 마세요.

==================================================
대답하지 말아야 하는 경우
==================================================

챗봇22.txt에 근거가 없는 질문이라면
억지로 답을 만들어내지 마세요.

다음과 같이 안내하세요.

"현재 제공된 업무자료에서는 정확한 내용을
확인하기 어렵습니다."

==================================================
답변의 핵심
==================================================

당신의 목표는 단순히 챗봇22.txt의 문장을
복사해서 보여주는 것이 아닙니다.

사용자의 질문을 이해하고,
챗봇22.txt에서 관련된 정보를 찾아,
필요한 정보를 연결하여,
일반인이 이해하기 쉬운 답변으로 만들어주세요.

하지만 모든 사실관계는 반드시
챗봇22.txt의 내용에 근거해야 합니다.

==================================================
업무자료
==================================================

${knowledge}

==================================================
업무자료 끝
==================================================
`;

    // =====================================================
    // 4. Gemini에게 질문
    // =====================================================

    const prompt = `
${systemInstruction}

사용자의 질문:

${message}

위 업무자료만을 근거로 사용자의 질문에 답변하세요.
`;

    // =====================================================
    // 5. Gemini 호출
    // =====================================================

    const result = await ai.models.generateContent({
      model: "gemini-3.5-flash",
      contents: prompt,
      config: {
        temperature: 0.2,
        maxOutputTokens: 1200,
      },
    });

    // =====================================================
    // 6. 답변 추출
    // =====================================================

    const answer = result.text;

    if (!answer) {
      return res.status(500).json({
        answer:
          "질문에 대한 답변을 받지 못했습니다.",
      });
    }

    // =====================================================
    // 7. 답변 반환
    // =====================================================

    return res.status(200).json({
      answer: answer.trim(),
    });

  } catch (error) {
    console.error("========== CHATBOT ERROR ==========");
    console.error(error);
    console.error("===================================");

    return res.status(500).json({
      answer:
        "서버에서 답변을 처리하는 중 문제가 발생했습니다.",
      error: error.message,
    });
  }
}
